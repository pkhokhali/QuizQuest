function submitQuiz(req, res, kind) {
  const user = req.user;
  const { quizId, answers } = req.body || {};

  // Offline quest sync support: Handle client-evaluated offline quests with anti-cheat caps
  const isOfflineSubmission = quizId === 999999 || req.body?.offlineTimestamp != null || req.body?.offlineScore != null;
  if (isOfflineSubmission) {
    const rawScore = Number(req.body?.offlineScore);
    const offlineScore = Math.max(0, Math.min(10, isNaN(rawScore) ? (Array.isArray(answers) ? answers.length : 0) : rawScore));
    const total = 10;
    const xpPerQ = kind === "daily" ? 10 : 8;
    const xpEarned = Math.min(150, offlineScore * xpPerQ);

    let streak = user.streak;
    let comeback = false;
    if (kind === "daily") {
      const last = user.last_quiz_date;
      if (last === daysAgo(1)) streak = user.streak + 1;
      else if (last !== today()) {
        if (last && last < daysAgo(3)) comeback = true;
        streak = 1;
      }
      db.prepare("UPDATE users SET streak = ?, best_streak = MAX(best_streak, ?), last_quiz_date = ? WHERE id = ?")
        .run(streak, streak, today(), user.id);
    }

    if (xpEarned > 0) {
      db.prepare("UPDATE users SET xp = xp + ? WHERE id = ?").run(xpEarned, user.id);
      const xpReason = kind === "daily" ? "offline_daily_quest" : "offline_practice_round";
      db.prepare("INSERT INTO xp_events (user_id, amount, reason, date) VALUES (?, ?, ?, ?)")
        .run(user.id, xpEarned, xpReason, today());
    }

    const fresh = db.prepare("SELECT * FROM users WHERE id = ?").get(user.id);
    const newAwards = checkAwards(user.id, { comeback }).map(({ earned, ...a }) => a);

    return res.json({
      score: offlineScore,
      total,
      xpEarned,
      xp: fresh.xp,
      level: levelForXp(fresh.xp),
      streak: fresh.streak,
      newAwards,
      correct: [],
      syncedOffline: true,
    });
  }

  const quiz = db.prepare("SELECT * FROM quizzes WHERE id = ? AND user_id = ? AND kind = ?").get(quizId, user.id, kind);
  if (!quiz) return res.status(404).json({ error: "Quiz not found" });
  if (quiz.completed) return res.status(400).json({ error: "Already completed" });
  if (!Array.isArray(answers)) return res.status(400).json({ error: "Answers required" });

  const ids = JSON.parse(quiz.question_ids);
  const ph = ids.map(() => "?").join(",");
  const questions = db.prepare(`SELECT * FROM questions WHERE id IN (${ph})`).all(...ids);
  const byId = Object.fromEntries(questions.map((q) => [q.id, q]));

  let score = 0;
  let xpEarned = 0;
  const correct = [];
  const logStmt = db.prepare(
    "INSERT INTO answer_log (user_id, question_id, subject, country, correct, source, date) VALUES (?, ?, ?, ?, ?, ?, ?)"
  );
  for (const qid of ids) {
    const q = byId[qid];
    if (!q) continue;

    // Robust answer lookup:
    // Match question ID loosely / numerically, and prioritize the latest non-null choice if duplicate entries exist
    const matchingAnswers = answers.filter((a) => a && Number(a.questionId) === Number(qid));
    let ans = null;
    if (matchingAnswers.length > 0) {
      const nonNullAns = matchingAnswers.filter((a) => a.choice !== null && a.choice !== undefined);
      ans = nonNullAns.length > 0 ? nonNullAns[nonNullAns.length - 1] : matchingAnswers[matchingAnswers.length - 1];
    }

    const order = optionOrder(quiz.id, qid);
    const correctIndex = order.indexOf(q.correct_index);
    correct.push({
      questionId: qid,
      correctIndex,
    });

    const isCorrect = ans != null && ans.choice !== null && ans.choice !== undefined && Number(ans.choice) === correctIndex;

    if (isCorrect) {
      score += 1;
      if (kind === "daily") {
        xpEarned += 10;
        if (typeof ans.timeMs === "number" && ans.timeMs < 5000) xpEarned += 5;
      } else {
        xpEarned += 8;
      }
    } else if (kind === "daily") {
      xpEarned -= 2; // quiet cost, never floors below 0 for the quiz overall
    }
    logStmt.run(user.id, qid, q.subject, q.country, isCorrect ? 1 : 0, kind, today());
  }
  xpEarned = Math.max(0, xpEarned);

  let streak = user.streak;
  let comeback = false;
  if (kind === "daily") {
    const last = user.last_quiz_date;
    if (last === daysAgo(1)) streak = user.streak + 1;
    else if (last !== today()) {
      if (last && last < daysAgo(3)) comeback = true;
      streak = 1;
    }
    db.prepare("UPDATE users SET streak = ?, best_streak = MAX(best_streak, ?), last_quiz_date = ? WHERE id = ?")
      .run(streak, streak, today(), user.id);
  }

  db.prepare("UPDATE quizzes SET completed = 1, score = ?, xp_earned = ? WHERE id = ?").run(score, xpEarned, quiz.id);
  db.prepare("UPDATE users SET xp = xp + ? WHERE id = ?").run(xpEarned, user.id);
  if (xpEarned > 0) {
    const xpReason = kind === "daily" ? "daily_quest" : kind === "practice" ? "practice_round" : "revenge_round";
    db.prepare("INSERT INTO xp_events (user_id, amount, reason, date) VALUES (?, ?, ?, ?)")
      .run(user.id, xpEarned, xpReason, today());
  }

  const fresh = db.prepare("SELECT * FROM users WHERE id = ?").get(user.id);
  const newAwards = checkAwards(user.id, { comeback }).map(({ earned, ...a }) => a);
  res.json({
    score,
    total: ids.length,
    xpEarned,
    xp: fresh.xp,
    level: levelForXp(fresh.xp),
    streak: fresh.streak,
    newAwards,
    correct,
  });
}

