function getDailyZipSpecs(dateStr) {
  const d = new Date(dateStr + "T00:00:00Z");
  const epoch = new Date("2026-01-01T00:00:00Z");
  const dayNum = Math.max(1, Math.floor((d.getTime() - epoch.getTime()) / 86400000) + 1);
  const dayOfWeek = d.getUTCDay();

  // Day-of-week Level-Up Progression:
  // Mon/Wed: 5x5 (Level 1: 7 checkpoints, 4 walls)
  // Tue/Thu/Fri: 6x6 (Level 2: 9 checkpoints, 7 walls)
  // Sun: 7x7 (Level 3: 12 checkpoints, 10 walls)
  // Sat (Weekend Grand Challenge): 8x8 (Master Level: 14 checkpoints, 12 walls)
  const size = dayOfWeek === 6 ? 8 : dayOfWeek === 0 ? 7 : [1, 3].includes(dayOfWeek) ? 5 : 6;
  const difficulty = size === 8 ? "hard" : size === 7 ? "hard" : size === 6 ? "medium" : "easy";

  let seed = (dayNum * 2654435761) >>> 0;
  const rng = () => {
    seed = (seed ^ (seed << 13)) >>> 0;
    seed = (seed ^ (seed >> 17)) >>> 0;
    seed = (seed ^ (seed << 5)) >>> 0;
    return (seed >>> 0) / 4294967296;
  };

  const total = size * size;
  const visited = Array.from({ length: size }, () => Array(size).fill(false));

  const neighbors = (r, c) => {
    const list = [];
    const deltas = [[-1, 0], [1, 0], [0, -1], [0, 1]];
    for (const [dr, dc] of deltas) {
      const nr = r + dr;
      const nc = c + dc;
      if (nr >= 0 && nr < size && nc >= 0 && nc < size && !visited[nr][nc]) {
        list.push({ row: nr, col: nc });
      }
    }
    return list;
  };

  const path = [];
  let backtrackSteps = 0;
  const MAX_BACKTRACK_STEPS = 2500;

  function backtrack(r, c) {
    if (++backtrackSteps > MAX_BACKTRACK_STEPS) return false;
    visited[r][c] = true;
    path.push({ row: r, col: c });
    if (path.length === total) return true;

    const nbrs = neighbors(r, c);
    for (const n of nbrs) {
      if (neighbors(n.row, n.col).length === 0 && path.length < total - 1) {
        visited[r][c] = false;
        path.pop();
        return false;
      }
    }

    nbrs.sort((a, b) => {
      const degA = neighbors(a.row, a.col).length;
      const degB = neighbors(b.row, b.col).length;
      if (degA !== degB) return degA - degB;
      return rng() - 0.5;
    });

    for (const n of nbrs) {
      if (backtrack(n.row, n.col)) return true;
    }
    visited[r][c] = false;
    path.pop();
    return false;
  }

  const corners = [
    { row: 0, col: 0 },
    { row: 0, col: size - 1 },
    { row: size - 1, col: 0 },
    { row: size - 1, col: size - 1 },
    { row: Math.floor(size / 2), col: 0 },
    { row: 0, col: Math.floor(size / 2) },
    { row: Math.floor(size / 2), col: size - 1 },
    { row: size - 1, col: Math.floor(size / 2) },
  ];
  const shuffledCorners = [...corners].sort(() => rng() - 0.5);
  let pathFound = false;
  for (const st of shuffledCorners) {
    backtrackSteps = 0;
    for (let r = 0; r < size; r++) visited[r].fill(false);
    path.length = 0;
    if (backtrack(st.row, st.col)) {
      pathFound = true;
      break;
    }
  }

  if (!pathFound) {
    path.length = 0;
    for (let r = 0; r < size; r++) {
      if (r % 2 === 0) {
        for (let c = 0; c < size; c++) path.push({ row: r, col: c });
      } else {
        for (let c = size - 1; c >= 0; c--) path.push({ row: r, col: c });
      }
    }
  }

  // Checkpoints: authentic LinkedIn number dilemma
  const targetCheckpoints = size === 5 ? 7 : size === 6 ? 9 : size === 7 ? 11 : 13;
  const numCheckpoints = Math.min(total, targetCheckpoints);

  const selectedIndices = [0];
  const innerCount = numCheckpoints - 2;
  if (innerCount > 0) {
    const idealStep = (total - 1) / (numCheckpoints - 1);
    for (let i = 1; i <= innerCount; i++) {
      const idealIdx = Math.round(i * idealStep);
      const jitter = Math.floor(rng() * 3) - 1;
      const minAllowed = selectedIndices[selectedIndices.length - 1] + 1;
      const maxAllowed = total - 1 - (innerCount - i + 1);
      const chosenIdx = Math.max(minAllowed, Math.min(maxAllowed, idealIdx + jitter));
      selectedIndices.push(chosenIdx);
    }
  }
  selectedIndices.push(total - 1);

  const checkpoints = {};
  const numbers = {};
  selectedIndices.forEach((idx, cpIdx) => {
    const cell = path[idx];
    const num = cpIdx + 1;
    checkpoints[`${cell.row}-${cell.col}`] = num;
    numbers[`${cell.row},${cell.col}`] = num;
  });
  const cpNum = selectedIndices.length;

  // Strategic connected obstacle walls (L-shapes, U-shapes, and corridor dividers)
  const targetWalls = size <= 5 ? 3 : size <= 6 ? 5 : size <= 7 ? 7 : 9;
  const walls = [];
  const wallsSet = new Set();
  const pathIndexMap = new Map();
  path.forEach((p, idx) => pathIndexMap.set(`${p.row},${p.col}`, idx));

  // Count walls surrounding each cell so no cell becomes enclosed
  const cellWallCount = new Map();
  const getWallCount = (r, c) => cellWallCount.get(`${r},${c}`) || 0;
  const incWallCount = (r, c) => cellWallCount.set(`${r},${c}`, getWallCount(r, c) + 1);

  const canPlaceWall = (rA, cA, rB, cB) => {
    const keyA = `${rA},${cA}`;
    const keyB = `${rB},${cB}`;
    const idxA = pathIndexMap.get(keyA);
    const idxB = pathIndexMap.get(keyB);
    if (idxA === undefined || idxB === undefined) return false;
    // Wall can NEVER cross consecutive steps in the solution path
    if (Math.abs(idxA - idxB) <= 1) return false;
    const wKey = keyA < keyB ? `${keyA}|${keyB}` : `${keyB}|${keyA}`;
    if (wallsSet.has(wKey)) return false;
    // Prevent blocking any cell completely (need at least 2 open exits)
    if (getWallCount(rA, cA) >= 2 || getWallCount(rB, cB) >= 2) return false;
    return true;
  };

  const addWall = (rA, cA, rB, cB) => {
    const keyA = `${rA},${cA}`;
    const keyB = `${rB},${cB}`;
    const wKey = keyA < keyB ? `${keyA}|${keyB}` : `${keyB}|${keyA}`;
    wallsSet.add(wKey);
    walls.push({ between: [keyA, keyB] });
    incWallCount(rA, cA);
    incWallCount(rB, cB);
  };

  // Grow walls into continuous multi-segment corridors / L-shapes
  for (let i = 0; i < path.length && walls.length < targetWalls; i++) {
    const p = path[i];
    const deltas = [[1, 0], [0, 1]];
    for (const [dr, dc] of deltas) {
      if (walls.length >= targetWalls) break;
      const nr = p.row + dr;
      const nc = p.col + dc;
      if (nr < size && nc < size && canPlaceWall(p.row, p.col, nr, nc)) {
        addWall(p.row, p.col, nr, nc);

        // Try chaining an extension (creating an L-corner or 2-3 segment run)
        const extensions = [
          // Continuation along same line
          dr !== 0 ? [p.row + dr, p.col, p.row + 2 * dr, p.col] : [p.row, p.col + dc, p.row, p.col + 2 * dc],
          // L-corner turn
          dr !== 0 ? [p.row, p.col, p.row, p.col + 1] : [p.row, p.col, p.row + 1, p.col],
          dr !== 0 ? [p.row, p.col, p.row, p.col - 1] : [p.row, p.col, p.row - 1, p.col],
        ];

        for (const [erA, ecA, erB, ecB] of extensions) {
          if (walls.length >= targetWalls) break;
          if (
            erA >= 0 && erA < size && ecA >= 0 && ecA < size &&
            erB >= 0 && erB < size && ecB >= 0 && ecB < size &&
            canPlaceWall(erA, ecA, erB, ecB)
          ) {
            addWall(erA, ecA, erB, ecB);
            break;
          }
        }
      }
    }
  }

  return {
    puzzleNum: dayNum,
    date: dateStr,
    size: { rows: size, cols: size },
    difficulty,
    totalCells: total,
    numbers,
    walls,
    solution: path.map((p) => `${p.row},${p.col}`),
    checkpoints,
    maxCheckpoint: cpNum,
    solutionPath: path,
  };
}

router.get("/zip/daily", (req, res) => {
  const dateStr = req.query.date || today();
  const specs = getDailyZipSpecs(dateStr);

  // Check if player has already submitted for today
  const myScoreRow = db
    .prepare("SELECT * FROM daily_zip_scores WHERE user_id = ? AND puzzle_date = ?")
    .get(req.user.id, dateStr);

  const myScore = myScoreRow
    ? {
        timeSeconds: myScoreRow.time_seconds,
        moves: myScoreRow.moves,
        stars: myScoreRow.stars,
        xpEarned: myScoreRow.xp_earned,
        completedAt: myScoreRow.created_at,
      }
    : null;

  // Fastest friend rival to beat
  const rivalRow = db
    .prepare(`
      SELECT u.id, u.name, u.avatar, s.time_seconds
      FROM daily_zip_scores s
      JOIN users u ON s.user_id = u.id
      JOIN friendships f ON (f.friend_id = s.user_id AND f.user_id = ?)
      WHERE s.puzzle_date = ?
      ORDER BY s.time_seconds ASC
      LIMIT 1
    `)
    .get(req.user.id, dateStr);

  const rivalToBeat = rivalRow
    ? {
        userId: rivalRow.id,
        name: rivalRow.name || "Friend",
        avatar: JSON.parse(rivalRow.avatar || "{}"),
        timeSeconds: rivalRow.time_seconds,
      }
    : null;

  res.json({
    ...specs,
    myScore,
    rivalToBeat,
  });
});

